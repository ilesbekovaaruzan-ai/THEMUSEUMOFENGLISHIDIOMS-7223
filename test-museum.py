from playwright.sync_api import sync_playwright, expect
import json

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/google-chrome',headless=True,args=['--no-sandbox','--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://localhost:4200')
    page.wait_for_timeout(1000)
    expect(page.get_by_role('heading',name='Names that became words.')).to_be_visible()
    page.screenshot(path='/home/user/desktop-final.png',full_page=True)
    page.get_by_role('button',name='ENTER THE MUSEUM',exact=True).click()
    expect(page.locator('.full-scene canvas')).to_be_visible()
    page.get_by_role('button',name='Exhibit directory',exact=True).click()
    expect(page.locator('.collection-card')).to_have_count(5)
    page.locator('.collection-card').nth(0).click()
    expect(page.get_by_role('heading',name='The knot nobody could untie',exact=True)).to_be_visible()
    page.locator('#reflection-answer').fill('I need to choose a university course.')
    for i in range(4):
        page.get_by_role('button',name='Next exhibit',exact=True).click()
        expect(page.locator('.exhibit-text h2')).to_be_visible()
    page.get_by_role('button',name='View your passport',exact=True).click()
    expect(page.get_by_text('All five exhibits discovered. You’ve completed the museum collection!')).to_be_visible()
    expect(page.locator('.passport-ticket .stamps .stamped')).to_have_count(5)
    page.get_by_role('button',name='Visit the learning studio',exact=True).click()
    for i,v in enumerate(['1','2','4']):page.locator(f'#mystery-{i}').select_option(v)
    page.get_by_role('button',name='Check answers',exact=True).click()
    expect(page.get_by_text('Your score: 3 / 3')).to_be_visible()
    page.get_by_role('button',name='Then & Now',exact=True).click()
    page.locator('input[name=now][value="1"]').check()
    page.get_by_role('button',name='Check answers',exact=True).click()
    expect(page.get_by_text('Your score: 0 / 1')).to_be_visible()
    page.get_by_role('button',name='Try again',exact=True).click()
    page.locator('input[name=now][value="4"]').check()
    page.get_by_role('button',name='Check answers',exact=True).click()
    page.locator('#own-sentence').fill('Learning to code takes time: Rome wasn’t built in a day.')
    page.get_by_role('button',name='Save my sentence',exact=True).click()
    expect(page.get_by_text('Sentence saved in your passport.',exact=False)).to_be_visible()
    page.get_by_role('button',name='Meaning Match',exact=True).click()
    for i in range(5):page.locator(f'#match-{i}').select_option(str(i+1))
    page.get_by_role('button',name='Check answers',exact=True).click()
    expect(page.get_by_text('All three activities complete.',exact=False)).to_be_visible()
    page.screenshot(path='/home/user/activities-test.png')
    page.get_by_role('button',name='Close panel',exact=True).click()
    page.get_by_role('button',name='All five discovered',exact=False).click()
    page.locator('#certificate-name').fill('Museum Visitor')
    with page.expect_download() as d:page.get_by_role('button',name='Download golden certificate',exact=False).click()
    assert d.value.suggested_filename=='Master-Curator-Certificate.svg'
    d.value.save_as('/home/user/test-certificate.svg')
    page.screenshot(path='/home/user/final-test.png')
    page.get_by_role('button',name='Close panel',exact=True).click()
    page.evaluate("window.dispatchEvent(new CustomEvent('museum-jump',{detail:4}))")
    page.wait_for_timeout(400)
    expect(page.locator('.museum-location h2')).to_have_text('The Roman Wing')
    page.keyboard.press('e')
    expect(page.get_by_role('heading',name='The emperor and the flames',exact=True)).to_be_visible()
    page.get_by_role('button',name='Close panel',exact=True).click()
    page.screenshot(path='/home/user/museum-test.png')
    page.reload()
    page.get_by_role('button',name='My passport',exact=False).click()
    expect(page.locator('.passport-ticket .stamps .stamped')).to_have_count(5)
    assert 'I need to choose' in page.evaluate("JSON.parse(localStorage.getItem('idiom-museum-v1')).responses['1']")
    print('DESKTOP: 5 exhibits, passport, reflections, 9/9 activities, retry, certificate, E interaction, Roman Wing, persistence: PASS')
    page.close()
    phone=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    mobile=phone.new_page();mobile.on('pageerror',lambda e:errors.append(str(e)))
    mobile.goto('http://localhost:4200');mobile.wait_for_timeout(800)
    mobile.screenshot(path='/home/user/mobile-final.png',full_page=True,timeout=60000)
    copy=mobile.locator('.hero-copy').bounding_box();scene=mobile.locator('.hero-scene').bounding_box()
    assert abs(copy['y']+copy['height']-scene['y'])<3
    assert mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    mobile.get_by_role('button',name='ENTER THE MUSEUM',exact=True).tap()
    expect(mobile.locator('.joystick')).to_be_visible()
    mobile.get_by_role('button',name='Exhibit directory',exact=True).tap()
    mobile.locator('.collection-card').nth(4).tap()
    expect(mobile.get_by_role('heading',name='The city of patience',exact=True)).to_be_visible()
    mobile.locator('#reflection-answer').fill('I am slowly building my English vocabulary.')
    mobile.screenshot(path='/home/user/mobile-exhibit.png')
    mobile.get_by_role('button',name='Close panel',exact=True).tap()
    mobile.screenshot(path='/home/user/mobile-museum.png')
    mobile.evaluate("window.dispatchEvent(new CustomEvent('museum-jump',{detail:5}))")
    mobile.wait_for_timeout(300)
    mobile.locator('.open-prompt').tap()
    expect(mobile.get_by_role('heading',name='The city of patience',exact=True)).to_be_visible()
    print('MOBILE: responsive layout, joystick, exhibit cards, touch-open prompt, reflections: PASS')
    print('PAGE ERRORS:',json.dumps(errors))
    assert not errors
    browser.close()